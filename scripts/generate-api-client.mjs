import { readFile, writeFile } from 'node:fs/promises';

const contractPath = new URL('../openapi/sesn.v1.yaml', import.meta.url);
const outputPath = new URL('../apps/web/src/api/generated.ts', import.meta.url);
const contract = await readFile(contractPath, 'utf8');

const requiredContractFragments = [
  'operationId: listProjects',
  'operationId: getProject',
  'operationId: getAuthContext',
  'enum: [draft, open, on_hold, closed, cancelled]',
  'enum: [recruiting, paused, filled, ended]',
  'required: [items, page]',
];

for (const fragment of requiredContractFragments) {
  if (!contract.includes(fragment)) {
    throw new Error(
      `OpenAPI contract is missing the expected fragment: ${fragment}`,
    );
  }
}

const generated = `// This file is generated by scripts/generate-api-client.mjs.
// Do not edit it directly. Run pnpm client:generate after changing OpenAPI.

export type ProjectStatus =
  'draft' | 'open' | 'on_hold' | 'closed' | 'cancelled';
export type RecruitmentStatus = 'recruiting' | 'paused' | 'filled' | 'ended';

export interface AuthContext {
  requiresMfa: boolean;
}

export interface Project {
  id: string;
  managementNo: string;
  projectName: string;
  summary: string | null;
  projectStatus: ProjectStatus;
  recruitmentStatus: RecruitmentStatus;
  plannedStartOn: string | null;
  plannedEndOn: string | null;
  updatedAt: string;
  rowVersion: number;
}

export interface ProjectList {
  items: Project[];
  page: { limit: number; nextCursor: string | null };
}

export interface ApiErrorBody {
  error: { code: string; message: string; requestId: string };
}

export interface ListProjectsQuery {
  managementNo?: string;
  status?: ProjectStatus;
  limit?: number;
}
`;

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== generated) {
    throw new Error('Generated API client is stale. Run pnpm client:generate.');
  }
} else {
  await writeFile(outputPath, generated);
}
